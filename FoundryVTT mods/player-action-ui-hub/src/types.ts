/**
 * 扇区的可用性三态（设计定档 §6.4）。三态都可点击——我们只提示，不禁止。
 * - normal : 无附加条件
 * - risky  : ⚠ 可以做但有额外检定/代价（如迟钝下施法要过平骰）。
 *            **保持正常亮度**，变暗会被读成"不该做"，那是把规则简化错了。
 * - gated  : ✖ 规则上此刻用不了（无 panache 的终结技、次数已用尽）。变暗。
 */
export type SectorState = "normal" | "risky" | "gated";

/** 轮盘上一个可点扇区的数据。UI 只认这个结构，不认 pf2e 的原始对象。 */
export interface SectorData {
    /** 稳定标识，用于回查执行目标 */
    id: string;
    /** 扇区上显示的名字 */
    label: string;
    /** 动作消耗，用于画 ◆ 记号；null = 不显示 */
    cost: "1" | "2" | "3" | "reaction" | "free" | null;
    /** 可用性状态 */
    state: SectorState;
    /** 完整原因，显示在中心毂；state 为 normal 时忽略。优先用系统 addenda 原文 */
    reason?: string;
    /** 短提示，**直接印在扇区上**（B 档强度，不用悬停就能看见） */
    badge?: string;
    /**
     * 悬停时显示在**中心毂**里的补充信息，例如技能的 "+11 Trained"。
     *
     * ★ 与 `badge` 的分工（Nous 2026-08-05 定）：
     *   - `badge` = **必须不看就知道**的东西（`◆ Draw`、`⟳` 反应、`◈ 2/2` 法术位余量），
     *     它们改变"这一格能不能点、点了要付什么代价"；
     *   - `detail` = **想知道才看**的参考值（技能修正、熟练度）。
     *
     *   全塞进 badge 会让每个扇区底下挂一行小字，既挤又难认 ——
     *   而中心毂本来就是信息呈现区，悬停时看它就够了。
     */
    detail?: string;
    /**
     * 条目图标路径（如 `systems/pf2e/icons/equipment/weapons/rapier.webp`）。
     *
     * ★ 有图标时扇区**只画图标不画名字**，名字交给中心毂在悬停时显示
     *   （Nous 2026-08-05 提出）。这是**结构上**避免长名字压出扇区，
     *   而不是靠缩字号硬塞 —— "Unarmed Attack" 那种长度怎么缩都别扭。
     */
    img?: string;
    /**
     * 这个条目的**多段变体**显示文字，第 0 项是第 1 击。
     *
     * ⚠ 文字**直接来自 pf2e**（`strike.variants[i].label`），不要自己拼"第 N 击"：
     *   findings-v0.1 §2 实测 label 本身就自带 MAP 文案
     *   （`["+13", "+9 (MAP -4)", "+5 (MAP -8)"]`），再拼一遍会把 MAP 显示两次。
     *
     * 每个条目各存一份而不是全盘共用一份，是因为**不同武器的加值不同**：
     * 共用第一把武器的数字，玩家悬停第二把时看到的就是假数字。
     */
    variantLabels?: string[];
    /**
     * 这一格不是一个动作，而是一个**出口**（去开角色卡之类）。
     *
     * ★ Nous 2026-08-07："全部用蓝色字写，提醒玩家去在表格里面添加 + 打开玩家表格。"
     *   蓝字是**类别记号不是装饰**：同一圈里混着"点了会掷骰"和"点了会开一个窗口"，
     *   不给区分的话玩家只能靠试。三态（normal/risky/gated）答的是"能不能点"，
     *   答不了"点了是哪一类事"，所以另开一根轴。
     *
     * ★ `aux` = **这一格不掷骰**（Nous 2026-08-08）：
     *   > "在 strike 里面会找到武器攻击，但是有些动作并不是攻击
     *   >  （draw / sheathe / change grip）……把这些部分的动作字体换成亮蓝色最好。"
     *   打击层里混着"打出去"和"摆弄武器"两类，图标又都没有 ——
     *   不给区分就只能靠读名字，而那正是每回合要快的地方。
     */
    /**
     * `link` = 出口（开角色卡的蓝 `+`）／`aux` = 点了不掷骰（拔刀装填的亮蓝）／
     * `confirm` = **确认执行**（选目标之后那个蓝色回车键，Nous 2026-08-08 定的形态）。
     *
     * ⚠ `confirm` 与 `link` 是**两种蓝**：`link` 说"点了会开一个窗"，
     *   `confirm` 说"点了这件事就真的发生了"。共用一个 tone 会让两者看着是一回事，
     *   而后者是不可逆的。
     * ⛔ 更实际的原因：`.pauih-label.tone-link` 的字号是 **20.5px** —— 那是为
     *   **画一个 `+` 号**定的。拿它写别的会横着冲出轮盘（2026-08-08 实机撞过）。
     */
    tone?: "link" | "aux" | "confirm";
    /**
     * 毂里显示的名字，与扇区上那个**不一样**时才给。
     *
     * ★ Nous 2026-08-07："我说的蓝色是中心圆盘上的，边盘上面的 ui 就只放一个蓝色的加号
     *   就够，本来就没地方放。"
     *   —— 环上一格宽约 50px，塞得下一个记号，塞不下一句话；
     *   而毂里有的是地方。**同一件事在两处各用各的说法**，不是重复。
     */
    hubLabel?: string;
    /**
     * 这一格的**完整说明**在哪（一个 uuid）。给了就把毂里那几行变成可点的，
     * 点开游戏自己的说明窗。
     *
     * ★ Nous 2026-08-07："把这种说明框变成（截断就截断）可以点击的，
     *   点击就会在游戏中打开说明。"
     *   ★ 这条把"截断"从一个**损失**变成一个**入口** ——
     *     毂里放得下多少就放多少，剩下的一点就有，不必再纠结上限。
     */
    infoUuid?: string;
    /**
     * 悬停这一格时，在**中心毂**里逐行写这一格的数值（伤害、弹药余量……）。
     *
     * ★★ **有图标的格子，图标下面一个字都不写 —— 数值全部进毂**（Nous 2026-08-08）：
     *
     *   > "这个又是一致性的下盘，icon 下面应该什么都不说，信息都应该在圆盘里面，
     *   >  伤害数值、map（已经有了）、伤害减值等等。"
     *
     * ★ 病根是我上一版挑错了修法：12.6 要的是**同一类信息要么每格都有、要么一格都没有**，
     *   我选了"每格都给"，于是扇区上出现了三种长度（`+14` / `+14 ◈1/1` / 空），
     *   **一格宽 46 单位**根本容不下"每格都给"这条路 —— 越给越不齐。
     *   ⇒ 正解是走另一头：**扇区上一律不写**，毂里逐行给全。
     *     毂是块屏，它容得下"每条都有"；扇区容不下，所以在扇区上追求一致必然失败。
     *
     * ⚠ 用数组而不是一个字符串：这几行是**并列的独立数值**，不是一段话。
     *   拼成一行会在长武器名/长伤害串上顶出毂外（SVG 的 text 不换行）。
     * ⚠ 行数有上限（见 `MAX_HUB_NOTES`），超出的不画 ——
     *   宁可少显示一条，也不要压住下面的状态区。
     */
    hubNotes?: string[];
}

/** 一层盘面。 */
export interface WheelLevel {
    /** 这一层的标题，显示在中心毂 */
    title: string;
    sectors: SectorData[];
    /** 是否显示返回扇区 */
    canGoBack: boolean;
    /**
     * 中心毂底部的变体翻选条（MAP 三段）；这一层不需要时省略。
     * 只有**下标**是全盘共用的状态——"现在是第几击"对整层成立；
     * 具体显示哪串文字则按悬停的扇区各取各的 `variantLabels`。
     */
    variant?: {
        /** 当前第几项，0 起 */
        index: number;
        /** 没有悬停任何扇区时显示的文字（取本层第一个条目的） */
        labels: string[];
    };
    /**
     * 分页状态；一页装得下的层省略即可。
     *
     * ★ `sectors` **始终存全量**，只渲染当前页 —— 翻页因此不必重新采集。
     *   重采集一次要重扫 70 条动作，而且会和双向绑定的重建打架。
     *
     * ⚠ 一层**不要同时开 `paging` 和 `variant`**：两者抢同一对胶囊箭头。
     *   `#onClick` 里分页优先。法术层将来若两者都需要，得另想办法（见 v0.3–v0.6 计划）。
     */
    paging?: {
        /** 当前页码，0 起。可以越界，取用时由 `pageOf` 回环。 */
        page: number;
        /**
         * **按组分页**（法术层：一页 = 一环）。给了就用它，不再按 `PAGE_SIZE` 一刀切。
         *
         * ★ Nous 2026-08-08 选的形态："分成环来翻页最好，这样和角色表单上面一模一样。"
         *   于是本来那个 `2 / 3` 的页码变成了 `2nd Rank ◈ 4/4` ——
         *   **同一个位置，从一个没意义的数变成了做决定要用的数**。
         *
         * ⚠ `from` / `count` 是**全量 `sectors` 里的下标区间**，不是页内位置。
         *   全模组的 `data-index` 一律指全量下标（见 wheel-app 那段注释），
         *   这里跟着同一个口径，才不用在点击分派里加特例。
         * ⚠ 一组放不下一页时由采集端再切，切出来的几页**沿用同一个标签**
         *   （还是那一环，不是新的一环）。
         */
        groups?: { label: string; badge?: string; from: number; count: number }[];
    };
    /**
     * **法术位点阵图**（Nous 2026-08-08）：一列一环、一点一位，用掉的变灰。
     *
     * ★ 它顶掉了原来那行 `2nd Rank ◈ 4/4`：那一行只说得了**当前这一环**，
     *   而选环时要比的是**各环还剩多少** —— 点阵一眼给全，占的地方还更小。
     * ⚠ `current` 是当前页对应的列下标；-1 = 当前页不对应任何一列（戏法页）。
     */
    slots?: { columns: { label: string; value: number; max: number }[]; current: number };
}
